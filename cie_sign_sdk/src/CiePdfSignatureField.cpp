#include "CiePdfSignatureField.h"
#include <algorithm>

using namespace PoDoFo;

CiePdfSignatureField::CiePdfSignatureField(PdfPage* page, const PdfRect& rect,
    PdfDocument* document, const PdfString& name, const char* subFilter)
    : PdfSignatureField(page, rect, document), document_(document), rect_(rect)
{
    SetFieldName(name);
    GetSignatureObject()->GetDictionary().AddKey("SubFilter",
        PdfName(subFilter && subFilter[0] ? subFilter : "adbe.pkcs7.detached"));
}

void CiePdfSignatureField::SetSignatureReason(const PdfString&, const PdfString& value)
{
    PdfSignatureField::SetSignatureReason(value);
}

void CiePdfSignatureField::SetSignatureLocation(const PdfString&, const PdfString& value)
{
    PdfSignatureField::SetSignatureLocation(value);
}

void CiePdfSignatureField::SetSignatureName(const PdfString&, const PdfString& value)
{
    GetSignatureObject()->GetDictionary().AddKey("Name", value);
}

void CiePdfSignatureField::SetSignatureSize(size_t size)
{
    // Use the exact beacon generated by the output device, rather than a
    // hard-coded placeholder that could drift from upstream's implementation.
    PdfOutputDevice sink;
    PdfSignOutputDevice signer(&sink);
    signer.SetSignatureSize(size);
    PdfSignatureField::SetSignature(*signer.GetSignatureBeacon());
}

void CiePdfSignatureField::SetAppearance(const char* imagePath, const char* description)
{
    PdfXObject appearance(PdfRect(0, 0, rect_.GetWidth(), rect_.GetHeight()), document_);
    PdfPainter painter;
    painter.SetPage(&appearance);
    if (imagePath && imagePath[0]) {
        PdfImage image(document_);
        image.LoadFromFile(imagePath);
        if (image.GetWidth() <= 0 || image.GetHeight() <= 0)
            PODOFO_RAISE_ERROR(ePdfError_InvalidDataType);
        double scale = std::min(rect_.GetWidth() / image.GetWidth(),
                                rect_.GetHeight() / image.GetHeight());
        painter.DrawImage((rect_.GetWidth() - image.GetWidth() * scale) / 2,
                          (rect_.GetHeight() - image.GetHeight() * scale) / 2,
                          &image, scale, scale);
    }
    if (description && description[0]) {
        PdfFont* font = document_->CreateFont("Helvetica");
        if (!font)
            PODOFO_RAISE_ERROR(ePdfError_InvalidHandle);
        font->SetFontSize(8);
        painter.SetFont(font);
        painter.DrawText(2, 2, PdfString(reinterpret_cast<const pdf_utf8*>(description)));
    }
    painter.FinishPage();
    SetAppearanceStream(&appearance);
}

void CiePdfSignatureField::SetGraphometricData(const PdfString& name,
    const PdfString& data, const PdfString& version)
{
    // The missing custom PoDoFo source prevents reproducing its private
    // biometric format. Reject the request instead of silently changing it.
    (void)name; (void)data; (void)version;
    PODOFO_RAISE_ERROR_INFO(ePdfError_UnsupportedFilter,
        "Graphometric signatures require the original custom PoDoFo implementation");
}
